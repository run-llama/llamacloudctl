// terraformAzure renders self-contained HCL for the Azure resources a
// customer-managed LlamaCloud install needs but that an infra team typically
// owns: a Blob Storage container per bucket, a user-assigned managed identity the
// platform pods federate to (Azure AD Workload Identity), the RBAC role
// assignment granting that identity blob data access, and the federated-identity
// credential that trusts the cluster's OIDC issuer for the platform
// ServiceAccounts. Output is deterministic (sorted buckets, stable identifiers).
//
// Two inputs the operator cannot derive from values are exposed as variables:
// resource_group_name (where the identity/role live) and oidc_issuer_url (the AKS
// cluster's OIDC issuer, `az aks show --query oidcIssuerProfile.issuerUrl`). The
// storage account name is a variable too (globally unique, 3–24 lowercase chars,
// so it cannot be derived from the namespace safely).
// terraformAzure composes the stdout stream from the same section renderers the
// --out-dir bundle uses, so the two can never drift. A plan with NO managed kinds
// produces byte-identical output to the earlier single-cloud monolith.
func terraformAzure(p Plan) string {
	var b strings.Builder
	b.WriteString(azureHeader(p))
	b.WriteString(azureTerraformBlock(p))
	b.WriteString(azureProviderBlock())
	b.WriteString(azureVariables(p))
	resourceHCL, _ := azureBaseResources(p)
	b.WriteString(resourceHCL)
	b.WriteString(azureManagedResources(p))
	b.WriteString(azureClientIDOutput())
	return b.String()
}

// azureHeader renders the leading comment block.
func azureHeader(p Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Terraform for a customer-managed LlamaCloud install on Azure.\n")
	fmt.Fprintf(&b, "# Generated by `llamacloudctl terraform --cloud azure` for namespace %q, location %q.\n", p.Namespace, p.Region)
	fmt.Fprintf(&b, "# Hand this to whoever owns your Azure subscription; apply with `terraform init && terraform apply`.\n")
	fmt.Fprintf(&b, "# It creates a Blob container per storage bucket and a user-assigned managed\n")
	fmt.Fprintf(&b, "# identity the platform pods federate to via Azure AD Workload Identity, so the\n")
	fmt.Fprintf(&b, "# pods read/write Blob storage with NO static account key. Annotate the platform\n")
	fmt.Fprintf(&b, "# service accounts with azure.workload.identity/client-id = the client_id output.\n\n")
	return b.String()
}

// azureTerraformBlock renders the required_providers block. hashicorp/random is
// added ONLY when managed kinds are present — the Azure path needs it for the
// PostgreSQL administrator password alone (Azure Managed Redis mints its own
// access keys), mirroring the gating awsTerraformBlock and gcpTerraformBlock use.
func azureTerraformBlock(p Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "terraform {\n")
	fmt.Fprintf(&b, "  required_providers {\n")
	fmt.Fprintf(&b, "    azurerm = {\n")
	fmt.Fprintf(&b, "      source  = \"hashicorp/azurerm\"\n")
	// azurerm 4.61 is the floor for the managed data services: >= 4.53 for
	// azurerm_managed_redis's public_network_access, >= 4.61 for its required
	// default_database block and updatable sku_name. Pinned below 5.0 so a
	// major-version schema break is an explicit bump rather than a surprise.
	fmt.Fprintf(&b, "      version = \">= 4.61, < 5.0\"\n")
	fmt.Fprintf(&b, "    }\n")
	if len(managedKinds(p)) > 0 {
		fmt.Fprintf(&b, "    random = {\n")
		fmt.Fprintf(&b, "      source  = \"hashicorp/random\"\n")
		fmt.Fprintf(&b, "      version = \"~> 3.5\"\n")
		fmt.Fprintf(&b, "    }\n")
	}
	fmt.Fprintf(&b, "  }\n}\n\n")
	return b.String()
}

// azureProviderBlock renders the provider block.
//
// azurerm 4.x resolves the target subscription from ARM_SUBSCRIPTION_ID or the
// signed-in az CLI account rather than defaulting silently, so say so — an
// operator moving from a 3.x bundle sees a different failure otherwise.
func azureProviderBlock() string {
	var b strings.Builder
	fmt.Fprintf(&b, "provider \"azurerm\" {\n")
	fmt.Fprintf(&b, "  # azurerm 4.x resolves the subscription from ARM_SUBSCRIPTION_ID or your `az login`\n")
	fmt.Fprintf(&b, "  # account. Export ARM_SUBSCRIPTION_ID, or set subscription_id here explicitly.\n")
	fmt.Fprintf(&b, "  features {}\n}\n\n")
	return b.String()
}

// azureVariables renders the operator-supplied inputs: the always-present
// resource group / location / storage account / OIDC issuer / namespace, plus
// (managed plans only) the EXISTING-networking inputs the PostgreSQL Flexible
// Server is integrated into.
func azureVariables(p Plan) string {
	var b strings.Builder
	// Inputs the operator must supply.
	fmt.Fprintf(&b, "variable \"resource_group_name\" {\n")
	fmt.Fprintf(&b, "  description = \"Resource group that holds the storage account, managed identity, and role assignment.\"\n")
	fmt.Fprintf(&b, "  type        = string\n}\n\n")
	fmt.Fprintf(&b, "variable \"location\" {\n")
	fmt.Fprintf(&b, "  description = \"Azure region for the resources.\"\n")
	fmt.Fprintf(&b, "  type        = string\n  default     = %q\n}\n\n", p.Region)
	fmt.Fprintf(&b, "variable \"storage_account_name\" {\n")
	fmt.Fprintf(&b, "  description = \"Globally-unique storage account name (3-24 lowercase alphanumeric chars).\"\n")
	fmt.Fprintf(&b, "  type        = string\n}\n\n")
	fmt.Fprintf(&b, "variable \"oidc_issuer_url\" {\n")
	fmt.Fprintf(&b, "  description = \"AKS cluster OIDC issuer URL (az aks show --query oidcIssuerProfile.issuerUrl -o tsv).\"\n")
	fmt.Fprintf(&b, "  type        = string\n}\n\n")
	fmt.Fprintf(&b, "variable \"k8s_namespace\" {\n")
	fmt.Fprintf(&b, "  description = \"Namespace the platform runs in; the federated credentials trust its service accounts.\"\n")
	fmt.Fprintf(&b, "  type        = string\n  default     = %q\n}\n\n", p.Namespace)
	b.WriteString(azureManagedVariables(p))
	return b.String()
}

// azureBaseResources renders the storage account, one container per bucket, the
// user-assigned managed identity, its blob role assignment and the federated
// identity credential — everything the Azure emitter produced before the managed
// data services existed. It also returns the per-bucket local names so the
// contract outputs can reference the containers.
func azureBaseResources(p Plan) (string, []tfName) {
	var b strings.Builder
	fmt.Fprintf(&b, "data \"azurerm_resource_group\" \"rg\" {\n  name = var.resource_group_name\n}\n\n")

	// Storage account + one container per bucket.
	fmt.Fprintf(&b, "resource \"azurerm_storage_account\" \"llama\" {\n")
	fmt.Fprintf(&b, "  name                     = var.storage_account_name\n")
	fmt.Fprintf(&b, "  resource_group_name      = data.azurerm_resource_group.rg.name\n")
	fmt.Fprintf(&b, "  location                 = var.location\n")
	fmt.Fprintf(&b, "  account_tier             = \"Standard\"\n")
	fmt.Fprintf(&b, "  account_replication_type = \"LRS\"\n}\n\n")

	seen := map[string]bool{}
	var names []tfName
	for _, bucket := range p.Buckets {
		local := uniqueLocal("container_"+sanitizeLocal(bucket), seen)
		names = append(names, tfName{local: local, bucket: bucket})
		fmt.Fprintf(&b, "resource \"azurerm_storage_container\" %q {\n", local)
		fmt.Fprintf(&b, "  name                  = %q\n", bucket)
		fmt.Fprintf(&b, "  storage_account_name  = azurerm_storage_account.llama.name\n")
		fmt.Fprintf(&b, "  container_access_type = \"private\"\n}\n\n")
	}

	// User-assigned managed identity the pods federate to.
	fmt.Fprintf(&b, "resource \"azurerm_user_assigned_identity\" \"llama\" {\n")
	fmt.Fprintf(&b, "  name                = \"llamacloud-%s\"\n", sanitizeLocal(p.Namespace))
	fmt.Fprintf(&b, "  resource_group_name = data.azurerm_resource_group.rg.name\n")
	fmt.Fprintf(&b, "  location            = var.location\n}\n\n")

	// Blob data access for that identity across the whole storage account.
	fmt.Fprintf(&b, "resource \"azurerm_role_assignment\" \"blob\" {\n")
	fmt.Fprintf(&b, "  scope                = azurerm_storage_account.llama.id\n")
	fmt.Fprintf(&b, "  role_definition_name = \"Storage Blob Data Contributor\"\n")
	fmt.Fprintf(&b, "  principal_id         = azurerm_user_assigned_identity.llama.principal_id\n}\n\n")

	// Federated identity credential: trust the AKS OIDC issuer for the platform SAs.
	// A named-SA subject is required per credential; emit one for the default
	// backend SA and instruct the operator to add more if their SAs differ.
	fmt.Fprintf(&b, "resource \"azurerm_federated_identity_credential\" \"llama\" {\n")
	fmt.Fprintf(&b, "  name                = \"llamacloud-%s\"\n", sanitizeLocal(p.Namespace))
	fmt.Fprintf(&b, "  resource_group_name = data.azurerm_resource_group.rg.name\n")
	fmt.Fprintf(&b, "  parent_id           = azurerm_user_assigned_identity.llama.id\n")
	fmt.Fprintf(&b, "  audience            = [\"api://AzureADTokenExchange\"]\n")
	fmt.Fprintf(&b, "  issuer              = var.oidc_issuer_url\n")
	fmt.Fprintf(&b, "  # One credential per service account. The platform annotates ~10 workload SAs;\n")
	fmt.Fprintf(&b, "  # add an azurerm_federated_identity_credential per SA subject you annotate.\n")
	fmt.Fprintf(&b, "  subject             = \"system:serviceaccount:${var.k8s_namespace}:llamacloud-backend\"\n}\n\n")
	return b.String(), names
}

// azureClientIDOutput renders the human-facing client_id output.
//
// In a MANAGED bundle this value is surfaced TWICE — here in main.tf as
// client_id, and again in outputs.tf as the frozen irsa_role_arn. That
// duplication is DELIBERATE, not an oversight: client_id is the Azure-native name
// this file's own header tells the operator to copy into a ServiceAccount
// annotation, while irsa_role_arn is the frozen, cloud-neutral contract slot
// ParseTerraformOutputs consumes. Renaming either would break one of those two
// consumers.
func azureClientIDOutput() string {
	var b strings.Builder
	fmt.Fprintf(&b, "output \"client_id\" {\n")
	fmt.Fprintf(&b, "  description = \"Annotate the platform service accounts with azure.workload.identity/client-id = this value.\"\n")
	fmt.Fprintf(&b, "  value       = azurerm_user_assigned_identity.llama.client_id\n}\n")
	return b.String()
}
