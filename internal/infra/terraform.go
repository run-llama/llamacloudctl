// Terraform renders self-contained HCL for the cloud resources a llamacloudctl
// install needs but that an infra team typically owns: the object-storage buckets
// and the workload-identity role/binding granting the platform pods runtime access
// to them. It dispatches to the per-cloud emitter (AWS S3 + IRSA, Azure Blob +
// managed identity, GCS + workload-identity binding). The output is deterministic
// (sorted buckets, stable identifiers) so re-running against the same values
// yields a byte-identical file, and it is written to be handed off verbatim —
// apply it with `terraform init && terraform apply`.
func Terraform(p Plan) string {
	switch p.EffectiveCloud() {
	case cloud.Azure:
		return terraformAzure(p)
	case cloud.GCP:
		return terraformGCP(p)
	default:
		return terraformAWS(p)
	}
}

// terraformAWS renders the AWS HCL stream by concatenating the per-section
// renderers. The non-managed stream (S3 buckets + IRSA IAM role/policy) is
// frozen byte-for-byte by the terraform_aws_nonmanaged golden test; the same
// sections are reassembled by TerraformFiles into the --out-dir bundle.
func terraformAWS(p Plan) string {
	var b strings.Builder
	b.WriteString(awsHeader(p))
	b.WriteString(awsTerraformBlock(p))
	b.WriteString(awsProviderBlock(p))
	b.WriteString(awsVariables(p))
	bucketHCL, names := awsBucketResources(p)
	b.WriteString(bucketHCL)
	b.WriteString(awsIAMResources(p, names))
	b.WriteString(awsManagedResources(p))
	b.WriteString(awsOutputs(p, names))
	return b.String()
}

// awsHeader renders the leading comment block describing what the file creates.
func awsHeader(p Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Terraform for a customer-managed LlamaCloud install.\n")
	fmt.Fprintf(&b, "# Generated by `llamacloudctl terraform` for namespace %q, region %q.\n", p.Namespace, p.Region)
	fmt.Fprintf(&b, "# Hand this to whoever owns your AWS account; apply with `terraform init && terraform apply`.\n")
	fmt.Fprintf(&b, "# It creates the S3 buckets the platform uses and an IRSA role granting the\n")
	fmt.Fprintf(&b, "# pods runtime access to them. Wire the role ARN output into your Helm values\n")
	fmt.Fprintf(&b, "# (annotate the platform service accounts with eks.amazonaws.com/role-arn) so\n")
	fmt.Fprintf(&b, "# the pods assume it.\n\n")
	return b.String()
}

// awsTerraformBlock renders the terraform { required_providers } block. The
// hashicorp/random provider is required ONLY when managed data services are
// emitted (their credentials are terraform-generated random_password resources).
func awsTerraformBlock(p Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "terraform {\n")
	fmt.Fprintf(&b, "  required_providers {\n")
	fmt.Fprintf(&b, "    aws = {\n")
	fmt.Fprintf(&b, "      source  = \"hashicorp/aws\"\n")
	fmt.Fprintf(&b, "      version = \"~> 5.0\"\n")
	fmt.Fprintf(&b, "    }\n")
	if len(managedKinds(p)) > 0 {
		fmt.Fprintf(&b, "    random = {\n")
		fmt.Fprintf(&b, "      source  = \"hashicorp/random\"\n")
		fmt.Fprintf(&b, "      version = \"~> 3.6\"\n")
		fmt.Fprintf(&b, "    }\n")
	}
	fmt.Fprintf(&b, "  }\n}\n\n")
	return b.String()
}

// awsProviderBlock renders the provider "aws" block.
func awsProviderBlock(p Plan) string {
	return fmt.Sprintf("provider \"aws\" {\n  region = %q\n}\n\n", p.Region)
}

// awsVariables renders every input variable: the IRSA inputs the operator cannot
// derive from values, plus (managed plans only) the existing-networking inputs
// the managed data services are placed into.
func awsVariables(p Plan) string {
	var b strings.Builder
	// Inputs the operator cannot derive from values: the cluster's OIDC provider
	// (for the IRSA trust) and the service account the pods run as.
	fmt.Fprintf(&b, "variable \"oidc_provider_arn\" {\n")
	fmt.Fprintf(&b, "  description = \"ARN of the EKS cluster's IAM OIDC provider (aws eks describe-cluster + iam list-open-id-connect-providers).\"\n")
	fmt.Fprintf(&b, "  type        = string\n}\n\n")
	fmt.Fprintf(&b, "variable \"oidc_provider_url\" {\n")
	fmt.Fprintf(&b, "  description = \"Host portion of the OIDC issuer URL, e.g. oidc.eks.%s.amazonaws.com/id/EXAMPLED539D4633E53DE1B71EXAMPLE.\"\n", p.Region)
	fmt.Fprintf(&b, "  type        = string\n}\n\n")
	fmt.Fprintf(&b, "variable \"k8s_namespace\" {\n")
	fmt.Fprintf(&b, "  description = \"Namespace the platform runs in. Every service account in it may assume the role (the platform annotates ~10 workload SAs with the same role ARN).\"\n")
	fmt.Fprintf(&b, "  type        = string\n  default     = %q\n}\n\n", p.Namespace)
	b.WriteString(awsManagedVariables(p))
	return b.String()
}

// awsBucketResources renders one aws_s3_bucket resource per unique bucket name
// and returns the tfName pairs the IAM policy references by ARN.
func awsBucketResources(p Plan) (string, []tfName) {
	var b strings.Builder
	names := make([]tfName, 0, len(p.Buckets))
	seen := map[string]bool{}
	for _, bucket := range p.Buckets {
		local := uniqueLocal("bucket_"+sanitizeLocal(bucket), seen)
		names = append(names, tfName{bucket: bucket, local: local})
		fmt.Fprintf(&b, "resource \"aws_s3_bucket\" %q {\n  bucket = %q\n}\n\n", local, bucket)
	}
	return b.String(), names
}

// awsIAMResources renders the IAM policy + IRSA role + attachment granting the
// platform pods runtime access to the buckets.
func awsIAMResources(p Plan, names []tfName) string {
	var b strings.Builder
	// IAM policy: the runtime S3 access the pods need against those buckets.
	fmt.Fprintf(&b, "resource \"aws_iam_policy\" \"llama_s3\" {\n")
	fmt.Fprintf(&b, "  name        = \"llamacloud-%s-s3\"\n", sanitizeLocal(p.Namespace))
	fmt.Fprintf(&b, "  description = \"Runtime S3 access for the LlamaCloud platform pods.\"\n")
	fmt.Fprintf(&b, "  policy      = jsonencode(%s)\n}\n\n", indentHCL(runtimePolicyDoc(names), 2))

	// IRSA role the pods assume, trusting the cluster OIDC provider for the SA.
	fmt.Fprintf(&b, "resource \"aws_iam_role\" \"llama_irsa\" {\n")
	fmt.Fprintf(&b, "  name = \"llamacloud-%s-irsa\"\n", sanitizeLocal(p.Namespace))
	fmt.Fprintf(&b, "  assume_role_policy = jsonencode(%s)\n}\n\n", indentHCL(trustPolicyDoc(), 2))

	fmt.Fprintf(&b, "resource \"aws_iam_role_policy_attachment\" \"llama_s3\" {\n")
	fmt.Fprintf(&b, "  role       = aws_iam_role.llama_irsa.name\n")
	fmt.Fprintf(&b, "  policy_arn = aws_iam_policy.llama_s3.arn\n}\n\n")
	return b.String()
}

// awsOutputs renders the output blocks for the stdout stream. The non-managed
// stream keeps its historical single irsa_role_arn output byte-identically
// (golden-tested — deliberately no bucket_names there); a managed stream
// carries the full frozen output contract (awsContractOutputs).
func awsOutputs(p Plan, names []tfName) string {
	if len(managedKinds(p)) > 0 {
		return awsContractOutputs(p, names)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "output \"irsa_role_arn\" {\n")
	fmt.Fprintf(&b, "  description = \"Annotate the platform service account with eks.amazonaws.com/role-arn = this value.\"\n")
	fmt.Fprintf(&b, "  value       = aws_iam_role.llama_irsa.arn\n}\n")
	return b.String()
}

// tfName pairs a bucket name with its Terraform-safe local resource name.
type tfName struct {
	bucket string
	local  string
}

// runtimePolicyDoc builds the IAM policy document granting RuntimeS3Actions on
// the buckets (list on the bucket ARN, object ops on <bucket>/*). Emitted with
// interpolated resource references so the ARNs track the created buckets.
func runtimePolicyDoc(names []tfName) string {
	bucketRefs := make([]string, 0, len(names))
	objectRefs := make([]string, 0, len(names))
	for _, n := range names {
		bucketRefs = append(bucketRefs, "${aws_s3_bucket."+n.local+".arn}")
		objectRefs = append(objectRefs, "${aws_s3_bucket."+n.local+".arn}/*")
	}
	doc := map[string]any{
		"Version": "2012-10-17",
		"Statement": []any{
			map[string]any{
				"Sid":      "LlamaCloudS3",
				"Effect":   "Allow",
				"Action":   toAny(RuntimeS3Actions),
				"Resource": toAny(append(bucketRefs, objectRefs...)),
			},
		},
	}
	return marshalDoc(doc)
}

// trustPolicyDoc builds the IRSA assume-role trust document: the cluster OIDC
// provider federated to the pods' service account subject.
func trustPolicyDoc() string {
	doc := map[string]any{
		"Version": "2012-10-17",
		"Statement": []any{
			map[string]any{
				"Effect": "Allow",
				"Principal": map[string]any{
					"Federated": "${var.oidc_provider_arn}",
				},
				"Action": "sts:AssumeRoleWithWebIdentity",
				// The platform annotates ~10 workload service accounts in the
				// namespace with this one role ARN, so the subject is matched with
				// StringLike against every SA in the namespace rather than a single
				// named SA. The audience is pinned exactly.
				"Condition": map[string]any{
					"StringLike": map[string]any{
						"${var.oidc_provider_url}:sub": "system:serviceaccount:${var.k8s_namespace}:*",
					},
					"StringEquals": map[string]any{
						"${var.oidc_provider_url}:aud": "sts.amazonaws.com",
					},
				},
			},
		},
	}
	return marshalDoc(doc)
}

// marshalDoc renders a policy document as indented JSON with map keys sorted, so
// the output is deterministic across runs (encoding/json sorts map keys).
func marshalDoc(doc map[string]any) string {
	out, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return "{}"
	}
	return string(out)
}

// indentHCL re-indents a multi-line JSON block so every line after the first is
// prefixed with n spaces, keeping the jsonencode(...) argument aligned under its
// attribute in the emitted HCL.
func indentHCL(s string, n int) string {
	pad := strings.Repeat(" ", n)
	lines := strings.Split(s, "\n")
	for i := 1; i < len(lines); i++ {
		lines[i] = pad + lines[i]
	}
	return strings.Join(lines, "\n")
}

// localSanitizer matches the characters not allowed in a Terraform identifier.
var localSanitizer = regexp.MustCompile(`[^a-z0-9_]`)

// sanitizeLocal lower-cases and replaces every non-identifier character with an
// underscore so any bucket/namespace string is usable in a resource local name.
func sanitizeLocal(s string) string {
	return localSanitizer.ReplaceAllString(strings.ToLower(s), "_")
}

// uniqueLocal returns base, or base_2, base_3, ... to guarantee the local name is
// unique even when two bucket names sanitize to the same identifier.
func uniqueLocal(base string, seen map[string]bool) string {
	cand := base
	for i := 2; seen[cand]; i++ {
		cand = fmt.Sprintf("%s_%d", base, i)
	}
	seen[cand] = true
	return cand
}

// toAny widens a []string to []any for embedding in a policy document map.
func toAny(ss []string) []any {
	out := make([]any, len(ss))
	for i, s := range ss {
		out[i] = s
	}
	return out
}
