package infra

import (
	"fmt"
	"strings"
)

// terraformGCP renders self-contained HCL for the Google Cloud resources a
// customer-managed LlamaCloud install needs but that an infra team typically
// owns: a GCS bucket per storage bucket, a Google service account (GSA) the
// platform pods impersonate via GKE Workload Identity, the IAM binding granting
// that GSA object access on the buckets, and the workloadIdentityUser binding
// that lets the Kubernetes service accounts impersonate the GSA. Output is
// deterministic (sorted buckets, stable identifiers).
//
// The project id and region are variables (project is not derivable from values;
// region defaults to the --region value). The GSA email output is what you
// annotate the platform service accounts with (iam.gke.io/gcp-service-account).
func terraformGCP(p Plan) string {
	var b strings.Builder
	b.WriteString(gcpHeader(p))
	b.WriteString(gcpTerraformBlock(p))
	b.WriteString(gcpVariables(p))
	b.WriteString(gcpProviderBlock())
	b.WriteString(gcpManagedLocals(p))
	resourceHCL, names := gcpBaseResources(p)
	b.WriteString(resourceHCL)
	b.WriteString(gcpManagedResources(p))
	b.WriteString(gcpOutputs(p, names))
	return b.String()
}

// gcpHeader renders the leading comment block describing what the file creates.
func gcpHeader(p Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Terraform for a customer-managed LlamaCloud install on Google Cloud.\n")
	fmt.Fprintf(&b, "# Generated by `llamacloudctl terraform --cloud gcp` for namespace %q, region %q.\n", p.Namespace, p.Region)
	fmt.Fprintf(&b, "# Hand this to whoever owns your GCP project; apply with `terraform init && terraform apply`.\n")
	fmt.Fprintf(&b, "# It creates a GCS bucket per storage bucket and a Google service account the\n")
	fmt.Fprintf(&b, "# platform pods impersonate via GKE Workload Identity, so the pods read/write GCS\n")
	fmt.Fprintf(&b, "# with NO static key. Annotate the platform service accounts with\n")
	fmt.Fprintf(&b, "# iam.gke.io/gcp-service-account = the identity output.\n")
	if len(managedKinds(p)) > 0 {
		fmt.Fprintf(&b, "#\n")
		fmt.Fprintf(&b, "# It ALSO creates the managed data services (Cloud SQL for PostgreSQL and/or\n")
		fmt.Fprintf(&b, "# Memorystore for Redis) in networking you already own. It creates NO networking\n")
		fmt.Fprintf(&b, "# and never creates a project.\n")
	}
	b.WriteString("\n")
	return b.String()
}

// gcpTerraformBlock renders the required_providers block. hashicorp/random is
// declared ONLY when managed data services are emitted — the Cloud SQL root
// password is a random_password. Memorystore needs none: it mints its own AUTH
// string service-side.
func gcpTerraformBlock(p Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "terraform {\n")
	fmt.Fprintf(&b, "  required_providers {\n")
	fmt.Fprintf(&b, "    google = {\n")
	fmt.Fprintf(&b, "      source  = \"hashicorp/google\"\n")
	fmt.Fprintf(&b, "      version = \"~> 6.0\"\n")
	fmt.Fprintf(&b, "    }\n")
	if len(managedKinds(p)) > 0 {
		fmt.Fprintf(&b, "    random = {\n")
		fmt.Fprintf(&b, "      source  = \"hashicorp/random\"\n")
		fmt.Fprintf(&b, "      version = \"~> 3.5\"\n")
		fmt.Fprintf(&b, "    }\n")
	}
	fmt.Fprintf(&b, "  }\n}\n\n")
	return b.String()
}

// gcpVariables renders the operator-supplied inputs: the always-present project /
// region / namespace, plus (managed plans only) the EXISTING-networking inputs the
// data services are placed into.
func gcpVariables(p Plan) string {
	var b strings.Builder
	fmt.Fprintf(&b, "variable \"project_id\" {\n")
	fmt.Fprintf(&b, "  description = \"GCP project id that holds the buckets and service account. This file never creates a project.\"\n")
	fmt.Fprintf(&b, "  type        = string\n}\n\n")
	fmt.Fprintf(&b, "variable \"region\" {\n")
	fmt.Fprintf(&b, "  description = \"GCP region for the GCS buckets.\"\n")
	fmt.Fprintf(&b, "  type        = string\n  default     = %q\n}\n\n", p.Region)
	fmt.Fprintf(&b, "variable \"k8s_namespace\" {\n")
	fmt.Fprintf(&b, "  description = \"Namespace the platform runs in; its service accounts impersonate the GSA.\"\n")
	fmt.Fprintf(&b, "  type        = string\n  default     = %q\n}\n\n", p.Namespace)
	b.WriteString(gcpManagedVariables(p))
	return b.String()
}

// gcpProviderBlock renders the google provider configuration.
func gcpProviderBlock() string {
	return "provider \"google\" {\n  project = var.project_id\n  region  = var.region\n}\n\n"
}

// gcpBaseResources renders the non-managed resources — a GCS bucket per storage
// bucket, the GSA the pods impersonate, the per-bucket object-admin bindings and
// the Workload Identity binding — and returns the bucket name pairs the outputs
// reference.
func gcpBaseResources(p Plan) (string, []tfName) {
	var b strings.Builder
	names := make([]tfName, 0, len(p.Buckets))
	seen := map[string]bool{}
	for _, bucket := range p.Buckets {
		local := uniqueLocal("bucket_"+sanitizeLocal(bucket), seen)
		names = append(names, tfName{bucket: bucket, local: local})
		fmt.Fprintf(&b, "resource \"google_storage_bucket\" %q {\n", local)
		fmt.Fprintf(&b, "  name                        = %q\n", bucket)
		fmt.Fprintf(&b, "  location                    = var.region\n")
		fmt.Fprintf(&b, "  uniform_bucket_level_access = true\n}\n\n")
	}

	// Google service account the pods impersonate.
	fmt.Fprintf(&b, "resource \"google_service_account\" \"llama\" {\n")
	fmt.Fprintf(&b, "  account_id   = \"llamacloud-%s\"\n", sanitizeAccountID(p.Namespace))
	fmt.Fprintf(&b, "  display_name = \"LlamaCloud platform (%s)\"\n}\n\n", p.Namespace)

	// Object admin on each bucket for that GSA.
	for _, n := range names {
		fmt.Fprintf(&b, "resource \"google_storage_bucket_iam_member\" %q {\n", uniqueLocal(n.local+"_iam", seen))
		fmt.Fprintf(&b, "  bucket = google_storage_bucket.%s.name\n", n.local)
		fmt.Fprintf(&b, "  role   = \"roles/storage.objectAdmin\"\n")
		fmt.Fprintf(&b, "  member = \"serviceAccount:${google_service_account.llama.email}\"\n}\n\n")
	}

	// Workload Identity: let every KSA in the namespace impersonate the GSA. The
	// platform annotates ~10 workload SAs with the same GSA, so bind the namespace's
	// SAs via the workloadIdentityUser role. GKE resolves the KSA->GSA mapping from
	// the iam.gke.io/gcp-service-account annotation on each KSA.
	fmt.Fprintf(&b, "resource \"google_service_account_iam_member\" \"wi\" {\n")
	fmt.Fprintf(&b, "  service_account_id = google_service_account.llama.name\n")
	fmt.Fprintf(&b, "  role               = \"roles/iam.workloadIdentityUser\"\n")
	fmt.Fprintf(&b, "  # One member per KSA. Add a google_service_account_iam_member per SA you annotate.\n")
	fmt.Fprintf(&b, "  member             = \"serviceAccount:${var.project_id}.svc.id.goog[${var.k8s_namespace}/llamacloud-backend]\"\n}\n\n")
	return b.String(), names
}

// sanitizeAccountID adapts a namespace to a GCP service-account account_id: 6–30
// chars, lowercase letters/digits/hyphens, starting with a letter. It lowercases,
// replaces invalid chars with hyphens, and pads a too-short id so the emitted HCL
// is always valid.
func sanitizeAccountID(ns string) string {
	s := sanitizeLocal(ns)              // lower + [^a-z0-9_] -> _
	s = strings.ReplaceAll(s, "_", "-") // account_id uses hyphens, not underscores
	s = strings.Trim(s, "-")            // no leading/trailing hyphen
	if s == "" {
		s = "ns"
	}
	// "llamacloud-" prefix (11 chars) already satisfies the leading-letter and
	// min-length rules; cap the suffix so the whole account_id stays <= 30 chars.
	if len(s) > 18 {
		s = s[:18]
	}
	return s
}

// gcpOutputs renders the output blocks for the GCP stream. The non-managed stream
// keeps its historical single gcp_service_account_email output byte-identically; a
// managed stream carries the full frozen output contract (gcpContractOutputs).
// This mirrors awsOutputs exactly.
func gcpOutputs(p Plan, names []tfName) string {
	if len(managedKinds(p)) > 0 {
		return gcpContractOutputs(p, names)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "output \"gcp_service_account_email\" {\n")
	fmt.Fprintf(&b, "  description = \"Annotate the platform service accounts with iam.gke.io/gcp-service-account = this value.\"\n")
	fmt.Fprintf(&b, "  value       = google_service_account.llama.email\n}\n")
	return b.String()
}
